export function unlockedStoryChapters(stage,verified){
 if(!verified)return 1;
 return Math.min(10,Math.max(1,Number.isInteger(stage)?stage:1));
}
export function initChristmasStory({openTab}){
 const $=id=>document.getElementById(id);
 const nav=$('story-chapter-list'),reader=$('story-reading'),count=$('story-progress-label'),
  meter=$('story-progress-fill'),state=$('story-state-note'),action=$('story-next-action'),
  banner=$('story-upgrade-banner'),mini=$('tab-story')?.querySelector('small');
 if(!nav||!reader||!count||!meter||!state||!action||!banner)throw Error('STORY_READER_MISSING');
 const make=(tag,className,text)=>{
  const node=document.createElement(tag);
  if(className)node.className=className;
  if(text!==undefined)node.textContent=String(text);
  return node;
 };
 let stage=1,verified=false,selected=1,needed=0,hasVerification=false;
 const choose=level=>{
  if(level<1||level>stage)return;
  selected=level;
  draw();
 };
 const draw=()=>{
  count.textContent=stage+' von 10 Teilen freigeschaltet';
  meter.style.width=(stage*10)+'%';
  $('story-progress-meter')?.setAttribute('aria-valuenow',String(stage));
  if(mini)mini.textContent=stage+' / 10 Teile'+(verified?'':' · Vorschau');
  state.textContent=verified?
   (stage===10?'🎄 Die Geschichte ist vollständig freigeschaltet.':
    '🎄 Der gemeinsame Weihnachtsbaum steht auf Stufe '+stage+'. Noch '+needed+' Gebäudeausbau'+(needed===1?'':'ten')+' bis zum nächsten Teil.'):
   '🔐 Die Einleitung ist frei lesbar. Weitere Teile werden erst durch den gespeicherten Ausbau des gemeinsamen Weihnachtsdorfs freigeschaltet.';
  nav.replaceChildren();
  for(const chapter of CHRISTMAS_STORY_CHAPTERS){
   const isOpen=chapter.level<=stage,isCurrent=chapter.level===selected;
   const button=make('button','story-chapter'+(isCurrent?' is-current':'')+(isOpen?' is-open':' is-locked'));
   button.type='button';button.disabled=!isOpen;
   button.setAttribute('aria-label',isOpen?
    'Teil '+chapter.level+': '+chapter.title+' lesen':'Teil '+chapter.level+' noch gesperrt');
   if(isCurrent)button.setAttribute('aria-current','step');
   const number=make('span','story-chapter-number',String(chapter.level).padStart(2,'0'));
   const title=make('span','story-chapter-name',isOpen?chapter.title:'Noch nicht enthüllt');
   const note=make('span','story-chapter-status',isOpen?(isCurrent?'📖 Wird gelesen':'✓ Freigeschaltet'):'🔒 Baumstufe '+chapter.level);
   button.append(number,title,note);
   if(isOpen)button.addEventListener('click',()=>choose(chapter.level));
   nav.append(button);
  }
  const chapter=CHRISTMAS_STORY_CHAPTERS[selected-1];
  reader.replaceChildren();
  const eyebrow=make('div','story-reading-eyebrow','✦ TEIL '+selected+' VON 10 · '+chapter.tree.toUpperCase());
  const title=make('h3','story-reading-title',chapter.icon+' '+chapter.title);
  const paragraphs=make('div','story-reading-paragraphs');
  for(const text of chapter.paragraphs)paragraphs.append(make('p','',text));
  reader.append(eyebrow,title,paragraphs);
  if(selected<stage){
   action.hidden=false;action.textContent='📖 Weiter zu Teil '+(selected+1);
   action.onclick=()=>choose(selected+1);
  }else if(stage<10){
   action.hidden=false;action.textContent='🏠 Zum Dorfausbau';
   action.onclick=()=>openTab('buildings');
  }else{
   action.hidden=false;action.textContent='🎄 Zurück zum Weihnachtsbaum';
   action.onclick=()=>openTab('tree');
  }
 };
 const render=({treeLevel=1,isVerified=false,remaining=0}={})=>{
  const next=unlockedStoryChapters(treeLevel,isVerified);
  const advanced=isVerified&&hasVerification&&verified&&next>stage;
  const firstLive=isVerified&&!hasVerification;
  if(isVerified)hasVerification=true;
  if(!isVerified)hasVerification=false;
  needed=Math.max(0,Number.isInteger(remaining)?remaining:0);
  if(advanced||firstLive||selected>next)selected=next;
  stage=next;verified=Boolean(isVerified);
  if(advanced){
   banner.textContent='✨ Neu freigeschaltet: Teil '+stage+' – '+CHRISTMAS_STORY_CHAPTERS[stage-1].title;
   banner.hidden=false;
  }else if(!isVerified)banner.hidden=true;
  draw();
 };
 render();
 return {render,openLatest:()=>choose(stage)};
}
